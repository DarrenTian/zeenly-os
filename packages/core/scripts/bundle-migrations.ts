/**
 * Writes drizzle/ into src/db/migrations.ts, so the kernel carries its
 * migrations as code rather than as a folder it has to find at runtime (a
 * bundled server or an installed package has no reliable path to one).
 * `pnpm db:generate` runs this after drizzle-kit; CI fails if it's stale.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { readMigrationFiles } from "drizzle-orm/migrator";
import prettier from "prettier";

const root = fileURLToPath(new URL("..", import.meta.url));
const journal = JSON.parse(
  readFileSync(`${root}/drizzle/meta/_journal.json`, "utf8"),
) as { entries: { tag: string }[] };
// Each with its file's name, so `zeenly-os migrate` can say what it applied.
const migrations = readMigrationFiles({
  migrationsFolder: `${root}/drizzle`,
}).map((m, i) => ({ tag: journal.entries[i].tag, ...m }));
const body = `// Generated by scripts/bundle-migrations.ts from drizzle/: don't edit.
import type { KernelMigration } from "./migrate";

export const MIGRATIONS: KernelMigration[] = ${JSON.stringify(migrations, null, 2)};
`;
// Formatted like the rest of the repository, so `pnpm format` leaves it alone
// and CI's regeneration matches the committed file byte for byte.
const config = (await prettier.resolveConfig(root)) ?? {};
writeFileSync(
  `${root}/src/db/migrations.ts`,
  await prettier.format(body, { ...config, parser: "typescript" }),
);
console.log(`src/db/migrations.ts: ${migrations.length} migrations`);
